const translationCache = {};

export const getUiTranslations = async (req, res, next) => {
    try {
        const lang = req.query.lang || 'en';

        if (lang === 'en') {
            return res.status(200).json(baseDictionary);
        }

        if (translationCache[lang]) {
            return res.status(200).json(translationCache[lang]);
        }

        const translatedDict = {};

        // Translate all values in the dictionary
        const keys = Object.keys(baseDictionary);
        const values = Object.values(baseDictionary);

        // We batch translations using translate array signature to speed it up
        try {
            const translatedValues = await translate(values, { to: lang });

            keys.forEach((key, index) => {
                translatedDict[key] = translatedValues[index].text;
            });
        } catch (translateError) {
            console.warn(`[WARN] Translation API failed for lang '${lang}'. Falling back to English.`);
            translatedDict = { ...baseDictionary };
        }

        // Cache the result
        translationCache[lang] = translatedDict;

        res.status(200).json(translatedDict);
    } catch (error) {
        console.error("UI Translation error:", error);
        // Fallback to base dictionary if unexpected error occurs
        res.status(200).json(baseDictionary);
    }
};
