i18n
    .use(LanguageDetector)
    .use(initReactI18next)
    .init({
        resources,
        fallbackLng: 'en',
        interpolation: {
            escapeValue: false, // react already safes from xss
        }
    });

// Listen for language changes and dynamically fetch new translation map
i18n.on('languageChanged', async (lng) => {
    if (lng === 'en') return;

    // Check if we already loaded it
    if (i18n.hasResourceBundle(lng, 'translation')) return;

    try {
        // Fetch from our new dynamic proxy backend map
        const response = await fetch(`http://localhost:8000/api/translations/ui?lang=${lng}`);
        const translations = await response.json();

        if (translations) {
            i18n.addResourceBundle(lng, 'translation', translations, true, true);
            // Trigger a re-render now that the resources are available
            i18n.changeLanguage(lng);
        }
    } catch (error) {
        console.error("Failed to fetch UI translations dynamically", error);
    }
});

export default i18n;
